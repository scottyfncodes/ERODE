// title → plan → set a smasher → release → run → results (iPhone-sized, touch emulation)
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto(url);
await page.waitForFunction(() => window.rockslide, null, { timeout: 120000 });
await page.waitForTimeout(1000);
await page.tap('#begin');
await page.waitForTimeout(1500);
await page.evaluate(() => window.rockslide.snapCamera());
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-1plan.png`, timeout: 120000 });
await page.evaluate(() => window.rockslide.select('tooth-a'));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-2select.png`, timeout: 120000 });
await page.evaluate(() => window.rockslide.action('split'));
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}-3placed.png`, timeout: 120000 });
await page.evaluate(() => window.rockslide.select(null));
await page.tap('#release');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}-4release.png`, timeout: 120000 });
// steer with a real touch drag on the canvas
const cdp = await ctx.newCDPSession(page);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 195, y: 420 }] });
for (let i = 1; i <= 6; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 195 + i * 8, y: 420 }] });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}-5steer.png`, timeout: 120000 });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
await page.evaluate(() => window.rockslide.finishNow());
await page.waitForTimeout(7000);
await page.screenshot({ path: `${out}-6results.png`, timeout: 120000 });
console.log(JSON.stringify(await page.evaluate(() => { const r = window.rockslide.result; return r && { score: r.score, stage: r.stage, trees: r.trees, landed: r.landed }; })));
await browser.close();
